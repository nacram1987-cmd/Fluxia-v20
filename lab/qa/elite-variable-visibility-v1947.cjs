'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const html=fs.readFileSync(path.join(__dirname,'../fluxia-elite-safari-datos-reales.html'),'utf8');
const a=html.indexOf('function variableVisibleInPeriod(');
const b=html.indexOf('function monthRecords(',a);
assert(a>=0&&b>a);
const ctx=vm.createContext({monthStatus:(r,ym)=>r.fecha&&r.fecha.slice(0,7)===ym?'match':'other'});
vm.runInContext(html.slice(a,b),ctx);
const fn=ctx.variableVisibleInPeriod;
assert.equal(fn({fecha:'2026-10-14',importe:7.5},'2026-10'),true);
assert.equal(fn({fecha:'2026-10-14',vinculoFijoId:'fijo'},'2026-10'),false);
assert.equal(fn({fecha:'2026-10-14',papelera:true},'2026-10'),false);
assert.equal(fn({fecha:'2026-10-14',tipoInterno:'traspaso'},'2026-10'),false);
assert.equal(fn({fecha:'2026-09-14'},'2026-10'),false);
assert(html.includes("const ELITE_SAFARI_VERSION='1.9.47'"));
assert(html.includes('variableVisibleInPeriod(x.record,selectedMonth)'));
for(const match of html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g))if(match[1])new vm.Script(match[1]);
console.log('PASS variable records visibility regression v1.9.47');
